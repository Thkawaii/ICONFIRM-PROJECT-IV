package models

import "time"

// ---------------------------------------------------------------------------
// ปิดใบอนุญาตอัตโนมัติ เมื่อหมดอายุแล้วไม่มีใครต่ออายุ
//
// ใบอนุญาตนำเข้าและนำออกไม่ได้ "ค้าง" อยู่ตลอดไป ในทางปฏิบัติ ถ้าผู้ใช้ไม่ต่ออายุ
// และไม่เพิ่มใบใหม่เข้าระบบ แปลว่างานของใบนั้นจบไปแล้ว — เครื่องที่ยังค้างอยู่บนใบ
// คือเครื่องที่ถูกยกเลิกหรือขายไม่ได้ ไม่ใช่เครื่องที่รอดำเนินการ
//
// ของเดิมระบบปิดใบได้ 2 ทางเท่านั้น คือติ๊กช่องเสร็จสิ้น หรือพิมพ์คำว่า "เสร็จสิ้น"
// ในช่องหมายเหตุ ใบที่ไม่มีใครแตะเลยจึงค้างเป็น "หมดอายุแล้ว" และถูกส่งอีเมล
// แจ้งเตือนซ้ำไปเรื่อย ๆ ไม่มีวันหยุด
//
// กติกาใหม่: หมดอายุมาแล้วเกิน N วันโดยไม่มีใบต่ออายุใบใหม่ → ถือว่าปิดจบ
// N ตั้งได้ด้วย LICENSE_AUTO_CLOSE_DAYS ในไฟล์ .env (ตั้ง 0 = ปิดการทำงานนี้)
//
// เป็นการ "ปิดจบ" ไม่ใช่ "ลบ" — ข้อมูลยังอยู่ครบ ดูย้อนหลังได้ทุกใบ
// และถ้าวันหนึ่งผู้ใช้ต่ออายุจริง ก็แค่อัปโหลดใบใหม่เข้ามา ใบนั้นจะกลับมาเดินต่อเอง
// ---------------------------------------------------------------------------

// DefaultLicenseAutoCloseDays = ค่าเริ่มต้นของระยะผ่อนผัน (วันปฏิทิน)
//
// 30 วันยาวพอให้งานที่ต่ออายุช้าจริง ๆ ยังทันถูกแจ้งเตือน
// แต่สั้นพอที่ใบซึ่งถูกทิ้งไปแล้วจะไม่รบกวนรายงานข้ามเดือน
const DefaultLicenseAutoCloseDays = 30

// LicenseAutoCloseBy / LicenseAutoCloseNote = ร่องรอยที่ระบบทิ้งไว้ตอนปิดใบให้
//
// เขียนให้คนอ่านออกว่าใครเป็นคนปิด เพราะช่อง CompletedBy ปกติเป็นชื่อผู้ใช้
// และ NoteMeansCompleted ต้องอ่านข้อความนี้แล้วตีความว่า "เสร็จสิ้น" ด้วย
// ไม่งั้นหน้าเว็บกับฐานข้อมูลจะเห็นไม่ตรงกันอีก
const (
	LicenseAutoCloseBy   = "ระบบ (ไม่ได้ต่ออายุ)"
	LicenseAutoCloseNote = "เสร็จสิ้น — ระบบปิดให้อัตโนมัติ เนื่องจากหมดอายุแล้วไม่ได้ต่ออายุ"
)

// LicenseAutoCloseDisabled = ค่าที่แปลว่า "ไม่ต้องปิดใบให้อัตโนมัติเลย"
//
// แยกออกจากเลข 0 เพราะสองอย่างนี้คนละความหมายกัน และของเดิมปนกันอยู่:
//
//	0   = พอหมดอายุก็ปิดเลย ไม่ต้องรอ
//	-1  = ไม่ปิดให้ ปล่อยค้างไว้ให้คนตัดสินใจเอง
//
// ตอนแรกใช้ 0 แทนการปิดการทำงาน เลยไม่มีทางสั่งให้ "ปิดทันทีที่หมดอายุ" ได้เลย
const LicenseAutoCloseDisabled = -1

// LicenseAutoCloseDue: ใบที่หมดอายุวันนี้เข้าเกณฑ์ปิดอัตโนมัติแล้วหรือยัง
//
// graceDays < 0 = ปิดการทำงาน · expiry = nil (ยังไม่รู้วันหมดอายุ) = ยังไม่ปิด
// เพราะใบที่ยังไม่ระบุวันที่ อาจเป็นใบที่เพิ่งยื่นและรอเลขจริงอยู่
func LicenseAutoCloseDue(expiry *time.Time, graceDays int, now time.Time) bool {
	if graceDays < 0 || expiry == nil {
		return false
	}
	return DaysBetween(now, *expiry) < -graceDays
}

// LicenseAutoCloseInDays: ใบที่หมดอายุแล้วแต่ยังไม่ถึงคิวปิด เหลืออีกกี่วันจึงจะถูกปิด
//
// มีไว้ตอบคำถามที่ผู้ใช้ถามบ่อยที่สุดเรื่องนี้ — "ใบหมดอายุไปแล้ว ทำไมยังไม่เสร็จสิ้น"
// ถ้าไม่บอกไว้บนหน้าจอ ระยะผ่อนผันจะกลายเป็นความลับที่มีแต่คนแก้ .env เท่านั้นที่รู้
//
// คืน nil เมื่อยังไม่หมดอายุ ปิดการทำงานอยู่ หรือถึงคิวปิดแล้ว
func LicenseAutoCloseInDays(expiry *time.Time, graceDays int, now time.Time) *int {
	if graceDays < 0 || expiry == nil {
		return nil
	}
	overdue := LicenseAutoCloseOverdueDays(expiry, now)
	if overdue == 0 || LicenseAutoCloseDue(expiry, graceDays, now) {
		return nil
	}
	left := graceDays - overdue + 1
	if left < 1 {
		left = 1
	}
	return &left
}

// LicenseAutoCloseOverdueDays: หมดอายุมาแล้วกี่วัน (0 ถ้ายังไม่หมดอายุ)
func LicenseAutoCloseOverdueDays(expiry *time.Time, now time.Time) int {
	if expiry == nil {
		return 0
	}
	if d := DaysBetween(now, *expiry); d < 0 {
		return -d
	}
	return 0
}
